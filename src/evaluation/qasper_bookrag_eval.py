from __future__ import annotations

import re
import string
from collections import Counter
from typing import Any, Dict, List, Sequence, Tuple

import httpx
from openai import OpenAI


# Keep this prompt aligned with BookRAG's Eval/utils/prompt.md so that answer
# extraction and 0/1 coarse judging follow the same style on Qasper.
BOOKRAG_QASPER_EVAL_PROMPT = """# Role and Goal
You are an AI evaluator. Your task is to assess a language model's response based on a given question and a ground truth "Correct Answer". You need to perform three actions:
1.  Extract the most direct answer from the "Model Response".
2.  Determine the data format of the extracted answer.
3.  Score the extracted answer's correctness by comparing it to the "Correct Answer".

# Input
- `Question`: The question asked to the model.
- `Correct Answer`: The ground truth answer.
- `Model Response`: The free-form text response generated by the model being evaluated.

# Rules for Extraction and Formatting
1.  **Source of Truth**: The `Extracted results` MUST come ONLY from the `Model Response`.
2.  **Allowed Formats**: The `Format` must be one of the following: `Integer`, `Float`, `String`, `List`.
3.  **Special Cases**:
    - If the response indicates the information is not in the documents, the `Extracted results` should be `Not answerable` and its `Format` is `String`.
    - If the response indicates it failed to process the input (e.g., blurry image, unreadable document), the `Extracted results` should be `Fail to answer` and its `Format` is `String`.

# Scoring Rules
- `Score: 1` (Correct): The `Extracted results` match the `Correct Answer`. (String comparison is case-insensitive. Numerical comparison is by value). A correct "Not answerable" or "Fail to answer" also gets a score of 1.
- `Score: 0` (Incorrect): The `Extracted results` do not match the `Correct Answer`.

# Output Format
Your output must be a structured block as follows. **Your response should be concise and contain ONLY this block, without any additional explanations or introductory text.**
```
Extracted results: [The answer extracted ONLY from the 'Model Response']
Format: [Integer, Float, String, or List]
Score: [1 for correct, 0 for incorrect]
```
"""


class BookRAGQasperAnswerExtractor:
    """
    BookRAG-compatible answer extractor for Qasper.

    BookRAG's Qasper evaluation first asks a strong judge model to normalize the
    model output into a concise answer string and a coarse 0/1 score. We mirror
    that behavior here, but allow the caller to pass base_url / api_key / model
    explicitly instead of relying on BookRAG's api.txt side file.
    """

    def __init__(
        self,
        *,
        base_url: str,
        api_key: str,
        model_name: str,
        timeout: float = 120.0,
    ) -> None:
        http_client = httpx.Client(timeout=timeout, trust_env=False)
        self.client = OpenAI(api_key=api_key, base_url=base_url, http_client=http_client)
        self.model_name = model_name
        self.system_prompt = BOOKRAG_QASPER_EVAL_PROMPT

    @staticmethod
    def parse_evaluation_output(llm_output: str) -> Dict[str, Any]:
        parsed_data: Dict[str, Any] = {}
        expected_keys = ["extracted results", "format", "score"]

        for line in llm_output.strip().split("\n"):
            if ":" not in line:
                continue
            key, value = line.split(":", 1)
            clean_key = key.strip().lower()
            clean_value = value.strip()
            if clean_key in expected_keys:
                parsed_data[clean_key] = clean_value

        for key in expected_keys:
            if key not in parsed_data:
                if key == "score":
                    parsed_data[key] = 0.0
                else:
                    parsed_data[key] = "Failed to extract"
        return parsed_data

    def extract(
        self,
        question: str,
        output: str,
        correct_answer: str,
    ) -> Tuple[str, str, str, float]:
        input_content = f"""
Question: {question}
Correct Answer: {correct_answer}
Model Response: {output}
"""
        messages = [
            {"role": "user", "content": self.system_prompt},
            {"role": "assistant", "content": input_content},
        ]
        parameters: Dict[str, Any] = {
            "model": self.model_name,
            "messages": messages,
            "temperature": 0.0,
            "max_tokens": 512,
        }
        if "qwen" in self.model_name.lower():
            parameters["extra_body"] = {"enable_thinking": False}

        response = self.client.chat.completions.create(**parameters)
        llm_res = response.choices[0].message.content or ""
        parsed = self.parse_evaluation_output(llm_res)
        score = parsed.get("score", 0.0)
        pred_answer = parsed.get("extracted results", "Failed to extract")
        pred_format = parsed.get("format", "Failed to extract")
        try:
            score_value = float(score)
        except Exception:
            score_value = 0.0
        return llm_res, pred_answer, pred_format, score_value


def normalize_answer(text: str) -> str:
    """
    Same normalization style as BookRAG's Qasper evaluation:
    lower, strip punctuation, strip articles, and squeeze whitespace.
    """

    def remove_articles(value: str) -> str:
        return re.sub(r"\b(a|an|the)\b", " ", value)

    def white_space_fix(value: str) -> str:
        return " ".join(value.split())

    def remove_punc(value: str) -> str:
        exclude = set(string.punctuation)
        return "".join(ch for ch in value if ch not in exclude)

    def lower(value: str) -> str:
        return value.lower()

    return white_space_fix(remove_articles(remove_punc(lower(text))))


def token_f1_score(prediction: str, ground_truth: str) -> float:
    prediction_tokens = normalize_answer(prediction).split()
    ground_truth_tokens = normalize_answer(ground_truth).split()
    common = Counter(prediction_tokens) & Counter(ground_truth_tokens)
    num_same = sum(common.values())
    if num_same == 0:
        return 0.0
    precision = 1.0 * num_same / len(prediction_tokens)
    recall = 1.0 * num_same / len(ground_truth_tokens)
    return (2 * precision * recall) / (precision + recall)


def get_answers_and_evidence(
    qa_info: Sequence[Dict[str, Any]],
    *,
    text_evidence_only: bool,
) -> List[Dict[str, Any]]:
    references: List[Dict[str, Any]] = []
    for answer_info in qa_info:
        if answer_info["unanswerable"]:
            references.append(
                {
                    "answer": "Not answerable",
                    "evidence": [],
                    "type": "none",
                    "answer_raw": "Not answerable",
                }
            )
            continue

        if answer_info["extractive_spans"]:
            answer = ", ".join(answer_info["extractive_spans"])
            answer_type = "extractive"
            answer_raw: Any = answer_info["extractive_spans"]
        elif answer_info["free_form_answer"]:
            answer = answer_info["free_form_answer"]
            answer_type = "abstractive"
            answer_raw = answer_info["free_form_answer"]
        elif answer_info["yes_no"]:
            answer = "Yes"
            answer_type = "boolean"
            answer_raw = "Yes"
        elif answer_info["yes_no"] is not None:
            answer = "No"
            answer_type = "boolean"
            answer_raw = "No"
        else:
            answer = "Not answerable"
            answer_type = "none"
            answer_raw = "Not answerable"

        if text_evidence_only:
            evidence = [
                text
                for text in answer_info["evidence"]
                if "FLOAT SELECTED" not in text
            ]
        else:
            evidence = answer_info["evidence"]
        references.append(
            {
                "answer": answer,
                "evidence": evidence,
                "type": answer_type,
                "answer_raw": answer_raw,
            }
        )
    return references


def get_accuracy(prediction: str, ground_truths: Sequence[str]) -> int:
    norm_pred = normalize_answer(prediction)
    for ground_truth in ground_truths:
        if normalize_answer(ground_truth) in norm_pred:
            return 1
    return 0


def eval_single_res(pred: str, gold_answers: Sequence[Dict[str, Any]]) -> Tuple[float, float]:
    """
    Mirror BookRAG's Qasper scoring:
    - accuracy: whether normalized gold answer is contained in normalized pred
    - f1: max token F1 across references
    """
    accuracy_score = 0.0
    f1_score = 0.0
    for gold in gold_answers:
        answer_raw = gold.get("answer_raw", "")
        if isinstance(answer_raw, str):
            answer_raw = [answer_raw]
        elif isinstance(answer_raw, int):
            answer_raw = [str(answer_raw)]
        acc = get_accuracy(pred, answer_raw)
        accuracy_score = max(accuracy_score, float(acc))

        f1 = token_f1_score(pred, gold.get("answer", ""))
        f1_score = max(f1_score, f1)
    return accuracy_score, f1_score

