from __future__ import annotations

import re
import string
from typing import Any, Dict, List, Sequence, Set, Tuple, Union

import httpx
import numpy as np
from openai import OpenAI
from scipy.optimize import linear_sum_assignment


BOOKRAG_M3DOC_EVAL_PROMPT = """# Role and Goal
You are an AI evaluator. Your task is to assess a language model's response based on a given question and a ground truth "Correct Answer". You need to perform three actions:
1.  Extract the most direct answer from the "Model Response".
2.  Determine the data format of the extracted answer.
3.  Score the extracted answer's correctness by comparing it to the "Correct Answer".

# Input
- `Question`: The question asked to the model.
- `Correct Answer`: The ground truth answer.
- `Model Response`: The free-form text response generated by the model being evaluated.

# Rules for Extraction and Formatting
1.  **Source of Truth**: The `Extracted results` MUST come ONLY from the `Model Response`.
2.  **Allowed Formats**: The `Format` must be one of the following: `Integer`, `Float`, `String`, `List`.
3.  **Special Cases**:
    - If the response indicates the information is not in the documents, the `Extracted results` should be `Not answerable` and its `Format` is `String`.
    - If the response indicates it failed to process the input (e.g., blurry image, unreadable document), the `Extracted results` should be `Fail to answer` and its `Format` is `String`.

# Scoring Rules
- `Score: 1` (Correct): The `Extracted results` match the `Correct Answer`. (String comparison is case-insensitive. Numerical comparison is by value). A correct "Not answerable" or "Fail to answer" also gets a score of 1.
- `Score: 0` (Incorrect): The `Extracted results` do not match the `Correct Answer`.

# Output Format
Your output must be a structured block as follows. **Your response should be concise and contain ONLY this block, without any additional explanations or introductory text.**
```
Extracted results: [The answer extracted ONLY from the 'Model Response']
Format: [Integer, Float, String, or List]
Score: [1 for correct, 0 for incorrect]
```

---
### Examples
---

**Example 1: List (Correct)**

Question: List the primary questions asked about the services in this report.
Correct Answer: ['Is the service safe?', 'Is the service effective?', 'Is the service caring?', 'Is the service responsive?', 'Is the service well-led?']
Model Response: The primary questions asked about the services in the report are:\n\n1. Is the service safe?\n2. Is the service effective?\n3. Is the service caring?\n4. Is the service responsive?\n5. Is the service well-led?
Extracted results: ['Is the service safe?', 'Is the service effective?', 'Is the service caring?', 'Is the service responsive?', 'Is the service well-led?']
Format: List
Score: 1

---

**Example 2: Integer (Incorrect)**

Question: How many regulations of the HSCA 2008 are breached in all according to this report?
Correct Answer: 10
Model Response: After reviewing the document, it seems there were 5 regulations breached by the provider.
Extracted results: 5
Format: Integer
Score: 0

---

**Example 3: String/YesNo (Correct)**

Question: Was 2008 the year Simon Brand directed the film Paraiso Travel?
Correct Answer: Yes
Model Response: Yes, 2008 was the year Simon Brand directed the film Paraiso Travel.
Extracted results: Yes
Format: String
Score: 1

---

**Example 4: Not Answerable (Correct)**

Question: According to the survey what is the percentage of Chinese who are paying more or about the same attention to politics after Trump's election?
Correct Answer: Not answerable
Model Response: The survey provided does not specify the percentage of Chinese individuals specifically.
Extracted results: Not answerable
Format: String
Score: 1

---

**Example 5: Fail to Answer (Correct)**

Question: How many quotations from male respondent over 50 years old are included in this report?
Correct Answer: Fail to answer
Model Response: The image you've provided appears to be a screenshot of a document, but the text is too small and blurry to read accurately. I am unable to process this file.
Extracted results: Fail to answer
Format: String
Score: 1

---
"""


class BookRAGM3DocAnswerExtractor:


    def __init__(
        self,
        *,
        base_url: str,
        api_key: str,
        model_name: str,
        timeout: float = 120.0,
    ) -> None:
        http_client = httpx.Client(timeout=timeout, trust_env=False)
        self.client = OpenAI(api_key=api_key, base_url=base_url, http_client=http_client)
        self.model_name = model_name
        self.system_prompt = BOOKRAG_M3DOC_EVAL_PROMPT

    @staticmethod
    def parse_evaluation_output(llm_output: str) -> Dict[str, Any]:
        parsed_data: Dict[str, Any] = {}
        expected_keys = ["extracted results", "format", "score"]

        for line in llm_output.strip().split("\n"):
            if ":" not in line:
                continue
            key, value = line.split(":", 1)
            clean_key = key.strip().lower()
            clean_value = value.strip()
            if clean_key in expected_keys:
                parsed_data[clean_key] = clean_value

        for key in expected_keys:
            if key not in parsed_data:
                if key == "score":
                    parsed_data[key] = 0.0
                else:
                    parsed_data[key] = "Failed to extract"
        return parsed_data

    def extract(
        self,
        question: str,
        output: str,
        correct_answer: str,
    ) -> Tuple[str, str, str, float]:
        input_content = f"""
Question: {question}
Correct Answer: {correct_answer}
Model Response: {output}
"""
        messages = [
            {"role": "user", "content": self.system_prompt},
            {"role": "assistant", "content": input_content},
        ]
        parameters: Dict[str, Any] = {
            "model": self.model_name,
            "messages": messages,
            "temperature": 0.0,
            "max_tokens": 512,
        }
        if "qwen" in self.model_name.lower():
            parameters["extra_body"] = {"enable_thinking": False}

        response = self.client.chat.completions.create(**parameters)
        llm_res = response.choices[0].message.content or ""
        parsed = self.parse_evaluation_output(llm_res)
        score = parsed.get("score", 0.0)
        pred_answer = parsed.get("extracted results", "Failed to extract")
        pred_format = parsed.get("format", "Failed to extract")
        try:
            score_value = float(score)
        except Exception:
            score_value = 0.0
        return llm_res, pred_answer, pred_format, score_value


def _remove_articles(text: str) -> str:
    regex = re.compile(r"\b(a|an|the)\b", re.UNICODE)
    return re.sub(regex, " ", text)


def _white_space_fix(text: str) -> str:
    return " ".join(text.split())


EXCLUDE = set(string.punctuation)


def _is_number(text: str) -> bool:
    try:
        float(text)
        return True
    except ValueError:
        return False


def _remove_punc(text: str) -> str:
    if _is_number(text):
        return text
    return "".join(ch for ch in text if ch not in EXCLUDE)


def _lower(text: str) -> str:
    return text.lower()


def _tokenize(text: str) -> List[str]:
    return re.split(" |-", text)


def _normalize_number(text: str) -> str:
    if _is_number(text):
        return str(float(text))
    return text


def _normalize_answer(text: str) -> str:
    parts = [
        _white_space_fix(
            _remove_articles(_normalize_number(_remove_punc(_lower(token))))
        )
        for token in _tokenize(str(text))
    ]
    parts = [part for part in parts if part.strip()]
    return " ".join(parts).strip()


def _answer_to_bags(
    answer: Union[str, List[str], Tuple[str, ...]],
) -> Tuple[List[str], List[Set[str]]]:
    if isinstance(answer, (list, tuple)):
        raw_spans = answer
    else:
        raw_spans = [answer]

    normalized_spans: List[str] = []
    token_bags: List[Set[str]] = []
    for raw_span in raw_spans:
        normalized_span = _normalize_answer(raw_span)
        normalized_spans.append(normalized_span)
        token_bags.append(set(normalized_span.split()))
    return normalized_spans, token_bags


def _compute_f1(predicted_bag: Set[str], gold_bag: Set[str]) -> float:
    intersection = len(gold_bag.intersection(predicted_bag))
    precision = 1.0 if not predicted_bag else intersection / float(len(predicted_bag))
    recall = 1.0 if not gold_bag else intersection / float(len(gold_bag))
    if precision == 0.0 and recall == 0.0:
        return 0.0
    return (2 * precision * recall) / (precision + recall)


def _match_numbers_if_present(gold_bag: Set[str], predicted_bag: Set[str]) -> bool:
    gold_numbers = {word for word in gold_bag if _is_number(word)}
    predicted_numbers = {word for word in predicted_bag if _is_number(word)}
    if (not gold_numbers) or gold_numbers.intersection(predicted_numbers):
        return True
    return False


def _align_bags(predicted: List[Set[str]], gold: List[Set[str]]) -> List[float]:
    scores = np.zeros([len(gold), len(predicted)])
    for gold_index, gold_item in enumerate(gold):
        for pred_index, pred_item in enumerate(predicted):
            if _match_numbers_if_present(gold_item, pred_item):
                scores[gold_index, pred_index] = _compute_f1(pred_item, gold_item)

    row_ind, col_ind = linear_sum_assignment(-scores)
    max_scores = np.zeros([max(len(gold), len(predicted))])
    for row, column in zip(row_ind, col_ind):
        max_scores[row] = max(max_scores[row], scores[row, column])
    return max_scores.tolist()


def list_em(predicted: Union[str, List[str]], gold: Union[str, List[str]]) -> float:
    predicted_bags = _answer_to_bags(predicted)
    gold_bags = _answer_to_bags(gold)
    if set(predicted_bags[0]) == set(gold_bags[0]) and len(predicted_bags[0]) == len(gold_bags[0]):
        return 1.0
    return 0.0


def list_f1(predicted: Union[str, List[str]], gold: Union[str, List[str]]) -> float:
    predicted_bags = _answer_to_bags(predicted)
    gold_bags = _answer_to_bags(gold)
    f1_per_bag = _align_bags(predicted_bags[1], gold_bags[1])
    return round(float(np.mean(f1_per_bag)), 2)
